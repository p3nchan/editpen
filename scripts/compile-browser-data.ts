// Build step: load + validate rules/profiles/lexicons with the Node loader and
// write src/browser/data.generated.ts for the browser entry.
// Usage: tsx scripts/compile-browser-data.ts [--rules-dir <path>]

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { loadLexicons, loadProfile, loadRules } from "../src/engine/loader.js";
import { defaultRulesDir } from "../src/engine/run.js";
import type { BrowserProfile, CompiledData, CompiledRule } from "../src/browser/types.js";

const outFile = fileURLToPath(new URL("../src/browser/data.generated.ts", import.meta.url));
const flag = process.argv.indexOf("--rules-dir");
const rulesDir = flag >= 0 ? path.resolve(process.argv[flag + 1] ?? "") : defaultRulesDir;
const profileIds: BrowserProfile[] = ["zh", "zh-tw"];

async function firstFailingExample(sourcePath: string): Promise<string | null> {
  const document: unknown = parse(await readFile(path.join(path.dirname(sourcePath), "fixtures.yaml"), "utf8"));
  const fixtures = (document as { fixtures?: unknown }).fixtures;
  if (!Array.isArray(fixtures)) {
    throw new Error(`Invalid fixtures next to ${sourcePath}`);
  }
  const failing = fixtures.find(
    (fixture: { expect?: unknown; text?: unknown }) => fixture.expect === "fail" && typeof fixture.text === "string",
  ) as { text: string } | undefined;
  return failing?.text ?? null;
}

const data: CompiledData = {
  schema: "editpen-browser-data/1",
  profiles: {} as CompiledData["profiles"],
  rules: [],
  lexicons: {},
};
const seen = new Set<string>();

for (const id of profileIds) {
  const profile = await loadProfile(rulesDir, id);
  const rules = await loadRules(rulesDir, profile);
  data.profiles[id] = { profile, ruleIds: rules.map((rule) => rule.id) };
  for (const [name, terms] of await loadLexicons(rulesDir, rules, profile)) {
    data.lexicons[name] = [...terms];
  }
  for (const rule of rules) {
    if (seen.has(rule.id)) {
      continue;
    }
    seen.add(rule.id);
    const { body: _body, sourcePath, ...engineRule } = rule;
    const compiled: CompiledRule = { ...engineRule, example: await firstFailingExample(sourcePath) };
    data.rules.push(compiled);
  }
}

const source = `// Generated by scripts/compile-browser-data.ts from rules/. Do not edit.
import type { CompiledData } from "./types.js";

export const data = JSON.parse(${JSON.stringify(JSON.stringify(data))}) as CompiledData;
`;
await writeFile(outFile, source);
process.stdout.write(
  `Compiled ${data.rules.length} rules, ${Object.keys(data.lexicons).length} lexicons for profiles ${profileIds.join(", ")} -> ${path.relative(process.cwd(), outFile)}\n`,
);
